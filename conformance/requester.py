# --------------------------------------------------------------------------- requests


def request_bytes(values: Dict[str, Any]) -> bytes:
    """A request as the stub builds it: the canonical JSON of its values."""
    return receipts.canonical_json(values)


def draw_values(rng, *, operation: str = OPERATION, n_items: Tuple[int, int] = (2, 6)
                ) -> Dict[str, Any]:
    """A fresh request. Recipient, amount and items are drawn from the seeded RNG; ``ref``, which
    makes every request distinct, comes from the operating system (UNSEEDED in P18)."""
    n = rng.randint(*n_items)
    items = sorted({f"sku-{rng.getrandbits(32):08x}" for _ in range(n)})
    while len(items) < n:
        items = sorted(set(items) | {f"sku-{rng.getrandbits(32):08x}"})
    return {"operation": operation, "ref": f"r-{secrets.token_hex(8)}",
            "recipient": f"acct-{rng.getrandbits(32):08x}@example.test",
            "amount": rng.randint(100, 99_999), "items": items}


def reserialise(values: Dict[str, Any]) -> bytes:
    """The same content in another serialisation: reversed key order, spaces and a newline. Built
    by hand, so no serialiser normalises it back."""
    import json
    parts = [f"{json.dumps(k)} : {json.dumps(values[k], ensure_ascii=False)}"
             for k in sorted(values, reverse=True)]
    return ("{ " + ",\n  ".join(parts) + " }\n").encode("utf-8")


def with_duplicate(values: Dict[str, Any], member: str, second: Any) -> bytes:
    """Canonical bytes of `values` with `member` written a second time, last, as `second`."""
    import json
    raw = request_bytes(values)
    return raw[:-1] + f",{json.dumps(member)}:{json.dumps(second)}}}".encode("utf-8")


def fullwidth(s: str) -> str:
    """ASCII letters and digits as their fullwidth forms, which NFKC folds back."""
    return "".join(chr(ord(c) - 0x21 + 0xFF01) if c.isascii() and c.isalnum() else c for c in s)


assert unicodedata.normalize("NFKC", fullwidth("acct-1a2b")) == "acct-1a2b"


def translate(values: Dict[str, Any], mapping: Dict[str, Any]) -> Dict[str, Any]:
    """A's values in B's vocabulary, through a declared mapping
    ``{"fields": {b_field: a_field}, "values": {a_field: {b_value: a_value}}}``."""
    to_b = {a: b for b, a in mapping["fields"].items()}
    vals = {a: {av: bv for bv, av in table.items()} for a, table in mapping.get("values", {}).items()}
    out = {}
    for a, v in values.items():
        out[to_b.get(a, a)] = vals.get(a, {}).get(v, v) if isinstance(v, str) else v
    return out


