"""The stub A for KRK-18 (P18): organisation A, played by the kit, and the transport it presents
requests on.

**What it is.** `StubRequester` holds A's own Ed25519 key (generated from the operating system,
never from the run's seed), builds requests as raw bytes, issues per-request authorisations in
the kit's format (`authz.SCHEMA`) or a wire profile, and writes, for each P18 variant, the plan
of presentations, transport actions and adapter hooks the variant needs (`plan`). `Transport`
presents raw bytes to B's adapter exactly once per presentation, with no retry of its own, can
drop B's answer after B has acted, can release several presentations at one moment, and keeps a
wire log of everything that left the kit.

**Never forge.** The stub signs only with its own keys. A changed payload is a changed body
presented beside an authorisation whose bytes are untouched. An authorisation for another
audience, a class, an expired window or declared parts is genuinely issued that way. Where a
fixture plays a sloppy A (``duplicate_key``, ``number_precision``) the stub genuinely signs the
digest that A would compute (`authz.lenient_digest`).

**Raw bytes end to end** (KRK-M37, KRK-M37). A fixture is built as bytes and never re-serialised:
the presentation carries the bytes, the wire log records their digest, and P18 compares them with
what B says it received.

**X4's parts** (KRK-19, `X4-WITHDRAWAL-WITHIN-T-DESIGN.md` §6.2), added without changing
anything X3 uses:

- **Grants and delegation** (`issue`, `delegate`, `regrant`): a grant (`status.GRANT_SCHEMA`)
  signed by A names the agent's key, the operation, a ceiling, the principal who granted it, a
  parent and a status entry. The agent's key is generated by the stub, from the operating system,
  like every other key. `under` builds one fresh request under a grant: a per-request
  authorisation in X3's format with the extra member ``grant_id``, signed by the agent's key
  (``signer="agent"``) or by A itself (``signer="a"``, presigned), beside the grant chain and,
  if asked, a stapled snapshot, all in headers outside the binding.
- **A status source** (`serve`, `set_source`, `fetch_local`): signed snapshots
  (`status.STATUS_SCHEMA`, or the `status.BITSTRING` profile) on ``/status/list`` and
  ``/status/item/<grant id>``, with ``Cache-Control: no-store`` (KRK-M57), and outage modes
  ``down`` (the connection is reset), ``hang`` (no answer), ``error`` (503), ``stale`` and
  ``rollback`` (an older snapshot the stub signed earlier, its original bytes). Every fetch by B
  is in `fetch_log` with its kit-clock start and end, the version served and the outcome. The
  kit's own baseline client reads ``/__baseline/status/list``, a path B is never given, so a
  ``stale`` fixture can serve B the old bytes while the baseline reads the current state.
- **Notices** (`push_to`): a signed notice for every change, to each registered receiver, logged
  in `push_log`; mode ``push-drop`` drops them and logs the drop.
- **Withdrawal** (`withdraw`, `suspend`, `narrow`, `withdraw_standing`, `reinstate`): each
  signs a new snapshot version and returns a `Withdrawal` whose ``t_commit`` is the kit-clock
  moment the source serves it from. `read_back` reads the published state in B's profile through
  the baseline client (KRK-M26, KRK-M50). A change the profile cannot express (a narrowing in a
  binary list) is recorded in `format_gaps`; `narrow` then withdraws and issues a narrower grant.
- **Snapshots and a clock offset** (the two fixtures P19 allows, and no others): every
  snapshot the stub signs is kept with its bytes (`snapshots`), so an older one can be served or
  stapled exactly as it was signed; `set_clock_offset` moves the stub's clock before it signs.
  Nothing is re-signed, altered or backdated after signing.

Every kit-clock time comes from ``clock`` (`timing.RealClock` unless a toy run passes a
`timing.VirtualClock`); `now()`, the stub's own wall clock with ``clock_offset_s``, is used only
for what it signs.
"""
