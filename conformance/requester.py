def request_bytes_loose(values: Dict[str, Any]) -> bytes:
    """Canonical layout without the safe-integer check: how a lenient A writes a request that
    carries an integer beyond 2**53 - 1 (``number_precision``)."""
    import json
    return json.dumps(values, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False).encode("utf-8")


# --------------------------------------------------------------------------- the transport


class AnswerLost(Exception):
    """Raised to an A whose answer the transport dropped after B acted (role-A family)."""


class Transport:
    """Presents raw bytes to B through `present_fn` (the adapter's `present`), exactly once per
    presentation: the transport has no retry of its own, adds nothing to the bytes or headers,
    and logs every presentation that leaves the kit (KRK-M38, KRK-M38)."""

    def __init__(self, present_fn: Callable[[Presentation], Dict[str, Any]], *,
                 clock: Callable[[], float] = time.time) -> None:
        self.present_fn = present_fn
        self.clock = clock
        self.wire_log: List[Dict[str, Any]] = []
        self.answers: Dict[str, Dict[str, Any]] = {}
        """pid -> B's answer, kept by the kit even when the answer was dropped before A."""
        self._lock = threading.Lock()

    def _log(self, p: Presentation, **more: Any) -> Dict[str, Any]:
        e = {"pid": p.pid, "endpoint": p.endpoint, "tenant": p.tenant,
             "request_sha256": receipts.sha256_ref(p.request), "request_len": len(p.request),
             "authorisation_sha256": (receipts.sha256_ref(p.authorisation.encode("utf-8"))
                                      if isinstance(p.authorisation, str) else None),
             "headers": dict(p.headers), "t_sent": self.clock(), **more}
        with self._lock:
            self.wire_log.append(e)
        return e

    def send(self, p: Presentation, *, drop_answer: bool = False,
             start_at: float = 0.0) -> Optional[Dict[str, Any]]:
        """Present once. Returns B's answer, or None when the answer is dropped (B has acted;
        A never reads what B said)."""
        if start_at:
            while self.clock() < start_at:
                time.sleep(min(0.002, max(0.0, start_at - self.clock())))
        e = self._log(p, dropped=drop_answer)
        try:
            ans = self.present_fn(p)
            if not isinstance(ans, dict):
                ans = {"status": None, "body": ans}
        except Exception as ex:  # noqa: BLE001 - B's failure is an answer, recorded as such
            ans = {"status": None, "raised": f"{type(ex).__name__}: {ex}"[:300]}
        e["t_answered"] = self.clock()
        e["answer_status"] = ans.get("status")
        with self._lock:
            self.answers[p.pid] = ans
        return None if drop_answer else ans

    def release_together(self, ps: Tuple[Presentation, ...], *,
                         delay_s: float = 0.1) -> List[Dict[str, Any]]:
        """Present every one of `ps` at one wall-clock moment, each on its own thread."""
        out: List[Optional[Dict[str, Any]]] = [None] * len(ps)
        start_at = self.clock() + delay_s
        gate = threading.Barrier(len(ps))

        def go(i: int) -> None:
            gate.wait()
            out[i] = self.send(ps[i], start_at=start_at)

        threads = [threading.Thread(target=go, args=(i,), daemon=True) for i in range(len(ps))]
        for t in threads:
            t.start()
        for t in threads:
            t.join(timeout=60)
        return [o or {"status": None, "raised": "no answer within 60 s"} for o in out]

    def sent(self, pid: str) -> int:
        """How many times presentation `pid` left the kit."""
        return sum(1 for e in self.wire_log if e["pid"] == pid)
